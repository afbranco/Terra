#!/usr/bin/env python3
"""Gera as tabelas de referência do site (docs/) a partir dos anexos da release (#91).

- --docs terra-docs.json: docs/_includes/generated/{terranet,terragrp}.md (os símbolos de cada VM,
  por grupo, com a disponibilidade por firmware);
- --catalog terrac-errors.json: docs/_includes/generated/codes.md (os códigos do terrac).

As páginas escritas à mão incluem esses arquivos com {% include generated/<nome>.md %}. Os gerados
ficam no repositório (o Pages publica o docs/ do master); o build da release confere que estão
atualizados (--check). Para regenerar: rodar com --out docs/_includes/generated.

Uso: genpages.py (--docs J | --catalog J) (--out PASTA | --check PASTA)
"""
import argparse
import json
import os
import sys

GROUP_TITLES = {
    "leds": "LEDs",
    "sensors": "Sensors",
    "custom": "Custom (loopback) events",
    "radio": "Radio",
    "queue": "Message queue",
    "ports": "Digital ports and interrupts",
    "mic": "Microphone and buzzer (MTS300 sensor board)",
    "fft": "FFT (experimental)",
    "group": "Groups and leader election",
    "aggregation": "Aggregation",
    "errors": "Runtime errors",
    "misc": "General",
}
PLATFORM_NAMES = {"tossim": "TOSSIM", "micaz": "micaz"}
REQUIRES_HINT = {
    "MSGQ": "firmware built with `MOD=MSGQ`",
    "FFT": "firmware built with `MOD=FFT`",
    "MIC": "firmware built for the MTS300 sensor board (`SENSOR=MTS300CA` or `MTS300CB`)",
    "PORTS": "mica family motes (not the simulator)",
}
VM_TITLES = {"net": "TerraNet", "grp": "TerraGrp"}
HEADER = ("<!-- Generated by docs/_tools/genpages.py from {src}. Do not edit: change the .defs.in, "
          "TerraVM/src/defs/descricoes.toml or terrac/errors.lua and regenerate. -->\n")


def cell(text):
    """Texto seguro numa célula de tabela Markdown: fora dos trechos `código`, < e > viram
    entidades e [ ] * _ são escapados (senão viram HTML, link ou ênfase)."""
    partes = (text or "").replace("\n", " ").split("`")
    for i in range(0, len(partes), 2):        # as partes pares estão fora do código
        t = partes[i].replace("\\", "\\\\")
        for c in "[]*_":
            t = t.replace(c, "\\" + c)
        partes[i] = t.replace("<", "&lt;").replace(">", "&gt;")
    return "`".join(partes).replace("|", "\\|").strip()


def code(text):
    return "`" + text + "`"


def signature(s):
    k = s["kind"]
    if k == "event" and s["direction"] == "emit":
        args = ", ".join(p["type"] for p in s["params"])
        return code("emit %s(%s)" % (s["name"], args))
    if k == "event":
        forms = []
        if s["id"] is not None:
            forms.append(code("await %s" % s["name"]))
        if s.get("filter"):
            forms.append(code("await %s(%s x)" % (s["name"], s["filter"]["type"])))
        return " or ".join(forms) + " → " + code(s["type"])
    if k == "function":
        params = ", ".join("%s %s" % (p["type"], p["name"]) for p in s["params"])
        attrs = " ".join(s["attrs"])
        return code("%s %s(%s)" % (s["returns"], s["name"], params)) + (" (%s)" % attrs if attrs else "")
    if k == "constant":
        v = s["value"]
        return code("%s = %s" % (s["name"], ("0x%X" % v) if v > 255 else v))
    if k == "macro":
        return code("%s(%s)" % (s["name"], ", ".join(p["name"] for p in s["params"])))
    if k == "type":
        return code("%s %s" % (s["type_kind"], s["name"]))
    raise SystemExit("kind desconhecido: %r" % k)


def availability(s):
    if s["platforms"]:
        return ", ".join(PLATFORM_NAMES.get(p, p) for p in s["platforms"])
    hint = "; ".join(REQUIRES_HINT.get(r, r) for r in s["requires"])
    return "no release firmware" + (" (%s)" % hint if hint else "")


def description(s):
    d = s["short"]
    if s["kind"] == "event" and s.get("filter"):
        d += " With `(x)`: only when x is %s." % s["filter"]["matches"]
    return d


def vm_page(docs, vm):
    syms = [s for s in docs["symbols"] if vm in s["variants"]]
    out = [HEADER.format(src="terra-docs.json")]
    allp = ", ".join(PLATFORM_NAMES.get(p, p) for p in docs["platforms"])
    out.append("Release firmware: %s. \"Available on\" lists the firmware whose `.defs` declares "
               "the symbol.\n" % allp)
    for g in docs["groups"]:
        gs = [s for s in syms if s["group"] == g]
        if not gs:
            continue
        out.append("\n### %s\n" % GROUP_TITLES[g])
        out.append("| Symbol | Description | Available on |")
        out.append("|---|---|---|")
        order = {"type": 0, "event": 1, "function": 2, "macro": 3, "constant": 4}
        gs.sort(key=lambda s: (order[s["kind"]], 0 if s.get("direction") == "emit" else 1,
                               s["name"].lower()))
        for s in gs:
            out.append("| %s | %s | %s |" % (cell(signature(s)), cell(description(s)),
                                             cell(availability(s))))
        notes = [s for s in gs if s.get("long") or s.get("example") or s["kind"] == "type"]
        for s in notes:
            out.append("\n**%s**%s" % (s["name"], (": " + s["long"]) if s.get("long") else ""))
            if s["kind"] == "type":
                out.append("\n| Field | Type | Description |")
                out.append("|---|---|---|")
                for f in s["fields"]:
                    out.append("| %s | %s | %s |" % (code(f["name"]), code(f["type"]), cell(f.get("short"))))
            if s.get("example"):
                # docs/_tools/checkexamples.lua compila cada exemplo com o .defs da VM
                out.append("\n<!-- check: ok%s -->\n```terra\n%s\n```" % (" grp" if vm == "grp" else "", s["example"]))
    unsafe = [s for s in syms if s.get("unsafe_with")]
    out.append("\n### Nondeterminism\n")
    if unsafe:
        out.append("Two trails that use these symbols in the same reaction give a nondeterminism "
                   "warning (W2xxx): the order of the effects is not defined.\n")
        out.append("| Symbol | Conflicts with |")
        out.append("|---|---|")
        for s in sorted(unsafe, key=lambda s: s["name"]):
            out.append("| %s | %s |" % (code(s["name"]), ", ".join(code(w) for w in s["unsafe_with"])))
    else:
        out.append("%s declares no `unsafe` pairs: the compiler does not warn about two trails "
                   "that use the same output event in the same reaction." % VM_TITLES[vm])
    return "\n".join(out) + "\n"


def codes_page(cat):
    out = [HEADER.format(src="terrac --catalog")]
    out.append("%d codes. The message is the text the compiler prints; `{name}` is replaced by "
               "the value (in `--diag=json`, also in `args`).\n" % len(cat["codes"]))
    for g in cat["groups"]:
        cs = [c for c in cat["codes"] if c["code"].startswith(g["prefix"])]
        if not cs:
            continue
        kind = "Errors" if g["prefix"][0] == "E" else "Warnings"
        out.append("\n### %s %sxxx: %s\n" % (kind, g["prefix"], g["name"]))
        out.append("| Code | Message |")
        out.append("|---|---|")
        for c in cs:
            msg = c["msg"].replace("`", "\x00")    # crases das mensagens não são código
            out.append('| <span id="%s"></span>%s | %s |' % (c["code"], c["code"],
                                                          cell(msg).replace("\x00", "\\`")))
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--docs")
    src.add_argument("--catalog")
    dst = ap.add_mutually_exclusive_group(required=True)
    dst.add_argument("--out")
    dst.add_argument("--check")
    a = ap.parse_args()
    if a.docs:
        d = json.load(open(a.docs))
        pages = {"terranet.md": vm_page(d, "net"), "terragrp.md": vm_page(d, "grp")}
    else:
        pages = {"codes.md": codes_page(json.load(open(a.catalog)))}
    pasta = a.out or a.check
    bad = []
    for nome, texto in pages.items():
        p = os.path.join(pasta, nome)
        if a.out:
            os.makedirs(pasta, exist_ok=True)
            with open(p, "w") as f:
                f.write(texto)
        elif not os.path.exists(p) or open(p).read() != texto:
            bad.append(nome)
    if bad:
        print("genpages: desatualizados em %s: %s (regenerar com --out)" % (pasta, " ".join(bad)))
        sys.exit(1)
    print("genpages: %s %s: OK" % ("gerados" if a.out else "conferidos", " ".join(sorted(pages))))


if __name__ == "__main__":
    main()
